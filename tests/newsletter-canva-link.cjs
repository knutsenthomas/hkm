const assert = require('node:assert/strict'), fs = require('node:fs'), vm = require('node:vm');
const { JSDOM } = require('jsdom');
const dom = new JSDOM('<img id="target" src="https://example.com/no.png">',{url:'https://hiskingdomministry.no/admin/admin-nyhetsbrev'});
const context={window:dom.window,document:dom.window.document,URL,console};
vm.createContext(context);
vm.runInContext(fs.readFileSync('admin/js/newsletter-canva-link.js','utf8').replaceAll('export function','function')+';globalThis.normalize=normalizeCanvaDesignUrl;globalThis.openCanva=openNewsletterCanvaLink;',context);
assert.equal(context.normalize('javascript:alert(1)'),null);
assert.equal(context.normalize('https://www.canva.com.attacker.test/design/123/edit'),null);
assert.equal(context.normalize('https://user:pass@www.canva.com/design/123/edit'),null);
assert.equal(context.normalize('https://www.canva.com/'),null);
assert.equal(context.normalize('https://canva.com/design/ABC123/edit'),'https://www.canva.com/design/ABC123/edit');
const image=dom.window.document.getElementById('target');
let syncs=0,saves=0;
const builder={currentEditorLang:'en',editorDocumentKey:'draft',syncUnifiedBlocks(){syncs++;},triggerAutosave(){saves++;}};
context.openCanva(builder,image);
const modal=dom.window.document.getElementById('newsletter-canva-link-modal');
const input=modal.querySelector('input[type=url]'),save=modal.querySelector('#save-canva-link');
input.value='https://www.canva.com/design/ABC123/edit';save.click();
assert.equal(image.dataset.canvaDesignUrl,input.value);assert.equal(saves,1);assert.equal(syncs,1);
assert.equal(image.src,'https://example.com/no.png','Saving a Canva link must not change the image');
assert.equal(modal.querySelector('#open-canva-design').hidden,false);
builder.currentEditorLang='no';input.value='https://www.canva.com/design/OTHER/edit';save.click();
assert.equal(saves,1,'Link changes must not cross languages');
assert.match(modal.querySelector('[role=status]').textContent,/språket er endret/);
modal.querySelector('#close-canva-link').click();assert.equal(dom.window.document.getElementById('newsletter-canva-link-modal'),null);
const builderSource=fs.readFileSync('admin/js/newsletter-builder.js','utf8');
assert.match(builderSource,/\['data-canva-design-url', 'data-canva-design-id'/);
assert.doesNotMatch(builderSource,/import.*newsletter-canva\.js/);
console.log('Passed: Canva URL validation, link saved without changing image, version guard and no live API dependency.');
